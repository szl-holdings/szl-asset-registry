"""Adversarial offline checks for card-generator vs producer lineage boundary."""
import importlib.util
from collections import Counter
import hashlib
import io
from contextlib import redirect_stdout
import json
from pathlib import Path
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location(
    "producer_provenance", ROOT / "tools" / "audit_producer_provenance.py"
)
audit_mod = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(audit_mod)


def row(rid="SZLHOLDINGS/fixture", method="card", repo="estate-cards", kind="models"):
    return {"id": rid, "type": kind, "method": method, "source_repo": repo}


class EvidenceTest(unittest.TestCase):
    def test_card_link_is_not_producer(self):
        result = audit_mod.classify(row(), {})
        self.assertEqual(result["producer_evidence_state"], "CARD_LINK_NOT_PRODUCER_EVIDENCE")
        self.assertIsNone(result["producer_repo"])
        self.assertFalse(result["producer_verified"])
        self.assertIsNone(result["card_generator_repo"])

    def test_override_generator_evidence_qualifies_card_only(self):
        result = audit_mod.classify(row(method="override"), {
            "SZLHOLDINGS/fixture": (
                "HF README case-card generated by szl-holdings/estate-cards weaver v0.1.0"
            )
        })
        self.assertEqual(result["card_generator_repo"], "estate-cards")
        self.assertIsNone(result["producer_repo"])
        self.assertFalse(result["producer_verified"])

    def test_override_without_producer_proof_stays_unattested(self):
        result = audit_mod.classify(row(method="override", repo="szl-gpu-bridge"), {
            "SZLHOLDINGS/fixture": "a link to szl-gpu-bridge readme"
        })
        self.assertEqual(result["producer_evidence_state"], "SOURCE_LINK_ONLY_NOT_PRODUCER_ATTESTED")
        self.assertFalse(result["producer_verified"])

    def test_name_match_never_attests_producer(self):
        result = audit_mod.classify(row(method="name", repo="szl-router"), {})
        self.assertIsNone(result["producer_repo"])
        self.assertFalse(result["producer_verified"])

    def test_unmapped_remains_unmapped(self):
        result = audit_mod.classify(row(method="unmapped", repo=None), {})
        self.assertEqual(result["producer_evidence_state"], "UNMAPPED_NO_PRODUCER")
        self.assertIsNone(result["legacy_source_repo"])

    def test_inconsistent_legacy_source_fails(self):
        with self.assertRaises(audit_mod.AuditHold):
            audit_mod.classify(row(method="card", repo=None), {})

    def test_duplicate_ids_refused(self):
        fixture = {"assets": [row(), row()], "coverage": {"total": 2, "mapped": 2, "unmapped": 0}}
        with self.assertRaises(audit_mod.AuditHold):
            audit_mod.audit(fixture, {})

    def test_same_name_different_asset_type_is_allowed(self):
        fixture = {
            "assets": [row(kind="models"), row(kind="datasets")],
            "coverage": {"total": 2, "mapped": 2, "unmapped": 0},
        }
        self.assertEqual(audit_mod.audit(fixture, {})["legacy_mapping_total"], 2)

    def test_unknown_evidence_key_is_rejected(self):
        fixture = {
            "assets": [row()],
            "coverage": {"total": 1, "mapped": 1, "unmapped": 0},
        }
        with self.assertRaises(audit_mod.AuditHold):
            audit_mod.audit(fixture, {"_evidence": {"SZLHOLDINGS/unknown": "case-card"}})

    def test_nonstrings_in_evidence_rejected(self):
        fixture = {
            "assets": [row()],
            "coverage": {"total": 1, "mapped": 1, "unmapped": 0},
        }
        with self.assertRaises(audit_mod.AuditHold):
            audit_mod.audit(fixture, {"_evidence": {"SZLHOLDINGS/fixture": 37}})

    def test_cross_kind_evidence_not_attributed_to_either(self):
        fixture = {
            "assets": [row(kind="models", method="override"), row(kind="spaces", method="override")],
            "coverage": {"total": 2, "mapped": 2, "unmapped": 0},
        }
        report = audit_mod.audit(fixture, {"_evidence": {
            "SZLHOLDINGS/fixture":
                "HF README case-card generated by szl-holdings/estate-cards weaver v0.1"
        }})
        self.assertEqual(report["card_generator_citations_present"], 0)

    def test_inconsistent_counts_refused(self):
        fixture = {"assets": [row()], "coverage": {"total": 1, "mapped": 0, "unmapped": 1}}
        with self.assertRaises(audit_mod.AuditHold):
            audit_mod.audit(fixture, {})

    def test_missing_asset_id_is_a_fail_closed_audit_hold(self):
        fixture = {
            "assets": [{"type": "models", "method": "card", "source_repo": "estate-cards"}],
            "coverage": {"total": 1, "mapped": 1, "unmapped": 0},
        }
        with self.assertRaises(audit_mod.AuditHold):
            audit_mod.audit(fixture, {})

    def test_missing_id_cli_returns_structured_hold(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            snapshot = root / "map.json"
            override = root / "overrides.json"
            snapshot.write_text(json.dumps({
                "assets": [{"type": "models", "method": "card", "source_repo": "estate-cards"}],
                "coverage": {"total": 1, "mapped": 1, "unmapped": 0},
            }), encoding="utf-8")
            override.write_text("{}", encoding="utf-8")
            output = io.StringIO()
            with redirect_stdout(output):
                code = audit_mod.main([
                    "--map", str(snapshot), "--overrides", str(override), "--audit-only"
                ])
            self.assertEqual(code, 2)
            self.assertEqual(json.loads(output.getvalue())["status"], "HOLD")

    def test_coverage_requires_exact_builtin_integer_types(self):
        for coverage in (
            {"total": True, "mapped": True, "unmapped": False},
            {"total": 1.0, "mapped": 1.0, "unmapped": 0.0},
        ):
            with self.subTest(coverage=coverage):
                with self.assertRaises(audit_mod.AuditHold):
                    audit_mod.audit({"assets": [row()], "coverage": coverage}, {})
        valid = {"total": 1, "mapped": 1, "unmapped": 0}
        self.assertEqual(
            audit_mod.audit({"assets": [row()], "coverage": valid}, {})["legacy_mapping_total"], 1
        )

    def test_real_frozen_snapshot_reclassification(self):
        mapping = json.loads((ROOT / "asset_map.json").read_text(encoding="utf-8"))
        overrides = json.loads((ROOT / "overrides.json").read_text(encoding="utf-8"))
        report = audit_mod.audit(mapping, overrides)
        self.assertEqual(report["legacy_mapping_total"], 397)
        self.assertEqual(report["legacy_link_coverage"], 356)
        self.assertEqual(report["card_link_not_producer_evidence"], 120)
        self.assertEqual(report["other_legacy_link_unattested"], 236)
        self.assertEqual(report["unmapped"], 41)
        self.assertEqual(report["producer_verified_total"], 0)
        self.assertEqual(report["card_generator_citations_present"], 65)
        self.assertFalse(report["producer_identity_claim_authorized"])

    def test_documented_legacy_denominator_matches_exact_frozen_map(self):
        raw = (ROOT / "asset_map.json").read_bytes()
        mapping = json.loads(raw)
        counts = Counter(row["method"] for row in mapping["assets"])
        coverage = mapping["coverage"]
        self.assertEqual(coverage["total"], len(mapping["assets"]))
        self.assertEqual(
            coverage["mapped"],
            counts["name"] + counts["card"] + counts["override"],
        )
        self.assertEqual(coverage["unmapped"], counts["unmapped"])
        readme = (ROOT / "README.md").read_text(encoding="utf-8")
        contract = (
            ROOT / "docs/PRODUCER_PROVENANCE_VS_CARD_LINKS.md"
        ).read_text(encoding="utf-8")
        digest = hashlib.sha256(raw).hexdigest()
        self.assertIn(f"{coverage['mapped']} with **legacy repository-link mappings**", readme)
        self.assertIn(
            f"({counts['name']} by repo-name match, {counts['card']} by GitHub link/card, "
            f"{counts['override']} by override)",
            readme,
        )
        self.assertIn(f"{coverage['unmapped']} UNMAPPED", readme)
        self.assertIn(f"superseded by the {coverage['unmapped']}-row current", readme)
        self.assertIn(f"{coverage['mapped']} non-null", contract)
        self.assertIn(f"{coverage['unmapped']} unmapped", contract)
        self.assertIn(digest, readme)
        self.assertIn(digest, contract)
        # A reported link must never be promoted to a producer attestation.
        self.assertIn("not verified producing-source identities", readme)
        self.assertIn("`producer_verified_total=0`", contract)

    def test_bad_duplicate_json_key_refused(self):
        with tempfile.TemporaryDirectory() as temp:
            path = Path(temp) / "a.json"
            path.write_text('{"assets":[],"assets":[]}', encoding="utf-8")
            with self.assertRaises(audit_mod.AuditHold):
                audit_mod._load_strict(path)


if __name__ == "__main__":
    unittest.main()
