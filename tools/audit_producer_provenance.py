#!/usr/bin/env python3
"""Offline fail-closed audit: a README/card link is not producing-source proof.

This does not modify asset_map.json or attest a model, dataset, Space, or producer.
Use an independently reviewed lineage protocol before setting producer_verified.
"""
from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path

SCHEMA = "szl.asset.producer-evidence-audit/v1"
ALLOWED_METHODS = {"name", "card", "override", "unmapped"}
ALLOWED_TYPES = {"models", "datasets", "spaces"}
GENERATOR = "estate-cards"


class AuditHold(ValueError):
    """Bad or inconsistent historical map: refuse to present assured counts."""


def _parse_strict_bytes(raw: bytes):
    def pairs(items):
        result = {}
        for key, value in items:
            if key in result:
                raise AuditHold("DUPLICATE_JSON_KEY")
            result[key] = value
        return result
    return json.loads(raw.decode("utf-8"), object_pairs_hook=pairs)


def _load_strict(path: Path):
    return _parse_strict_bytes(path.read_bytes())


def classify(record: dict, evidence: dict) -> dict:
    """Produce a *separate* status without silently rewriting legacy source_repo."""
    if not isinstance(record, dict):
        raise AuditHold("INVALID_ROW")
    rid, kind, method = (record.get(k) for k in ("id", "type", "method"))
    repo = record.get("source_repo")
    if not isinstance(rid, str) or not rid.startswith("SZLHOLDINGS/"):
        raise AuditHold("INVALID_ASSET_ID")
    if kind not in ALLOWED_TYPES or method not in ALLOWED_METHODS:
        raise AuditHold("INVALID_TYPE_OR_METHOD")
    if (method == "unmapped") != (repo is None):
        raise AuditHold("LEGACY_MAPPING_INCONSISTENT")
    if repo is not None and (not isinstance(repo, str) or not repo.strip()):
        raise AuditHold("INVALID_LEGACY_SOURCE_REPO")
    card_only = repo == GENERATOR and method in ("card", "override")
    cited = evidence.get(rid)
    card_generator_cited = (
        card_only and method == "override" and isinstance(cited, str)
        and "HF README case-card generated by szl-holdings/estate-cards weaver" in cited
    )
    if card_only:
        state = "CARD_LINK_NOT_PRODUCER_EVIDENCE"
    elif repo is None:
        state = "UNMAPPED_NO_PRODUCER"
    else:
        state = "SOURCE_LINK_ONLY_NOT_PRODUCER_ATTESTED"
    return {
        "id": rid,
        "type": kind,
        "legacy_mapping_method": method,
        "legacy_source_repo": repo,
        "producer_repo": None,
        "producer_verified": False,
        "producer_evidence_state": state,
        "card_generator_repo": GENERATOR if card_generator_cited else None,
        "card_generator_evidence_is_producer_evidence": False,
    }


def audit(asset_map: dict, overrides: dict) -> dict:
    if not isinstance(asset_map, dict) or not isinstance(asset_map.get("assets"), list):
        raise AuditHold("INVALID_LEGACY_MAP")
    if not isinstance(overrides, dict):
        raise AuditHold("INVALID_OVERRIDES")
    evidence = overrides.get("_evidence", {})
    if not isinstance(evidence, dict):
        raise AuditHold("INVALID_EVIDENCE_TABLE")
    assets = asset_map["assets"]
    if not assets:
        raise AuditHold("EMPTY_MAP")
    # Hub permits the same namespace/name in different repo types.
    typed_ids = [(a.get("type"), a.get("id")) for a in assets if isinstance(a, dict)]
    if len(typed_ids) != len(assets) or len(set(typed_ids)) != len(typed_ids):
        raise AuditHold("DUPLICATE_OR_INVALID_ASSETS")
    ids = {a["id"] for a in assets}
    if any(type(key) is not str or key not in ids or type(value) is not str
           or not value.strip() for key, value in evidence.items()):
        raise AuditHold("INVALID_OR_UNSCOPED_GENERATOR_EVIDENCE")
    # Historical override evidence is keyed by name, not type. If a name exists
    # in two asset types, do not attribute its generator citation to either.
    name_counts = Counter(a["id"] for a in assets)
    safe_evidence = {key: value for key, value in evidence.items() if name_counts[key] == 1}
    results = [classify(a, safe_evidence) for a in assets]
    coverage = asset_map.get("coverage", {})
    methods = Counter(r["legacy_mapping_method"] for r in results)
    expected_total = len(results)
    expected_mapped = expected_total - methods["unmapped"]
    if not isinstance(coverage, dict) or any(
        coverage.get(k) != n for k, n in (
            ("total", expected_total), ("mapped", expected_mapped),
            ("unmapped", methods["unmapped"])
        )
    ):
        raise AuditHold("LEGACY_COVERAGE_MISMATCH")
    if any(r["producer_verified"] or r["producer_repo"] is not None for r in results):
        raise AuditHold("UNSUPPORTED_PRODUCER_ATTESTATION")
    classes = Counter(r["producer_evidence_state"] for r in results)
    return {
        "schema": SCHEMA,
        "scope": "OFFLINE_SNAPSHOT_ONLY_NO_LIVE_HF_VERIFICATION",
        "legacy_mapping_total": expected_total,
        "legacy_link_coverage": expected_mapped,
        "producer_verified_total": 0,
        "card_link_not_producer_evidence": classes["CARD_LINK_NOT_PRODUCER_EVIDENCE"],
        "other_legacy_link_unattested": classes["SOURCE_LINK_ONLY_NOT_PRODUCER_ATTESTED"],
        "unmapped": classes["UNMAPPED_NO_PRODUCER"],
        "card_generator_citations_present": sum(r["card_generator_repo"] == GENERATOR for r in results),
        "producer_identity_claim_authorized": False,
        "legacy_map_modified": False,
        "assets": results,
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--map", type=Path, default=Path("asset_map.json"))
    ap.add_argument("--overrides", type=Path, default=Path("overrides.json"))
    ap.add_argument("--audit-only", action="store_true", help="Validate and summarize, no output file.")
    ap.add_argument("--out", type=Path, help="Write exclusive-create unsigned, offline audit JSON.")
    args = ap.parse_args(argv)
    if args.audit_only and args.out:
        ap.error("--audit-only and --out are mutually exclusive")
    try:
        raw_map, raw_overrides = args.map.read_bytes(), args.overrides.read_bytes()
        mapping = _parse_strict_bytes(raw_map)
        override = _parse_strict_bytes(raw_overrides)
        output = audit(mapping, override)
        output["input_map_sha256"] = hashlib.sha256(raw_map).hexdigest()
        output["input_overrides_sha256"] = hashlib.sha256(raw_overrides).hexdigest()
        compact = {k: v for k, v in output.items() if k != "assets"}
        if args.out:
            with args.out.open("x", encoding="utf-8") as f:
                json.dump(output, f, indent=2, sort_keys=True)
                f.write("\n")
        print(json.dumps(compact, sort_keys=True))
        return 0
    except (AuditHold, OSError, ValueError, TypeError) as e:
        print(json.dumps({"status": "HOLD", "reason": str(e) if isinstance(e, AuditHold) else type(e).__name__}))
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
